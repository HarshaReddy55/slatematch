"""ML module: real training pipeline on payment history.
Two models: (1) payment-delay regression, (2) deduction-validity classification.
History is generated by a labelled synthetic generator (seed data) OR loaded
from real history rows with the same schema. Metrics are computed on a
time-ordered holdout and stored per model version."""
import numpy as np, json, os, pickle
from sklearn.ensemble import GradientBoostingRegressor, GradientBoostingClassifier
from sklearn.metrics import mean_absolute_error, roc_auc_score

CUSTOMER_PROFILES = {  # delay propensity baked into the generator; models must LEARN it from features
    "Apex Manufacturing": 2.0, "BluePeak Electronics": 9.0, "Cascade Chemicals": 16.0, "Summit Logistics": 5.0, "Northgate Foods": 22.0, "HarborView Pharma": 1.0,
}

def generate_history(n=1200, seed=42):
    rng = np.random.default_rng(seed)
    customers = list(CUSTOMER_PROFILES)
    rows = []
    for i in range(n):
        cust = customers[rng.integers(0, len(customers))]
        terms = int(rng.choice([15, 30, 30, 45, 60]))
        amount = float(rng.lognormal(9.5, 0.8)) * 100  # cents-ish scale -> dollars below
        month = int(rng.integers(1, 13))
        base_delay = CUSTOMER_PROFILES[cust]
        # amount effect: 2 extra days per $10,000 of invoice value
        # (0.000002 per cent). At 0.00002 the effect ran 100x too hot:
        # a $96k invoice "learned" to pay 200+ days late, which made
        # every forecast downstream of this model meaningless.
        delay = base_delay + 0.000002 * amount + (3.0 if month in (3, 6, 9, 12) else 0.0) + rng.normal(0, 3.5)
        delay = max(-5.0, delay)
        # deduction validity: valid when POD clean and claim size moderate relative to history
        pod_clean = rng.random() < 0.6
        claim_ratio = float(rng.uniform(0.2, 3.0))
        p_valid = 0.85 if pod_clean else 0.3
        if claim_ratio > 2.0: p_valid -= 0.25
        valid = 1 if rng.random() < max(0.05, min(0.97, p_valid)) else 0
        rows.append({"customer": cust, "terms_days": terms, "amount_cents": int(amount),
                     "month": month, "delay_days": round(float(delay), 2),
                     "pod_clean": int(pod_clean), "claim_ratio": round(claim_ratio, 3), "valid": valid,
                     "seq": i})
    return rows

def _features_delay(rows):
    custs = sorted(CUSTOMER_PROFILES)
    X, y = [], []
    for r in rows:
        onehot = [1.0 if r["customer"] == c else 0.0 for c in custs]
        X.append(onehot + [r["terms_days"], np.log1p(r["amount_cents"]), r["month"],
                           1.0 if r["month"] in (3, 6, 9, 12) else 0.0])
        y.append(r["delay_days"])
    return np.array(X), np.array(y)

def _features_validity(rows):
    X, y = [], []
    for r in rows:
        X.append([r["pod_clean"], r["claim_ratio"], np.log1p(r["amount_cents"]), r["terms_days"]])
        y.append(r["valid"])
    return np.array(X), np.array(y)

def train_all(rows=None, artifact_dir=None):
    rows = rows or generate_history()
    rows = sorted(rows, key=lambda r: r["seq"])
    cut = int(len(rows) * 0.8)
    train, test = rows[:cut], rows[cut:]
    Xtr, ytr = _features_delay(train); Xte, yte = _features_delay(test)
    delay_model = GradientBoostingRegressor(random_state=7).fit(Xtr, ytr)
    pred = delay_model.predict(Xte)
    mae = float(mean_absolute_error(yte, pred))
    baseline_mae = float(mean_absolute_error(yte, np.full_like(yte, np.mean(ytr))))
    Xtr2, ytr2 = _features_validity(train); Xte2, yte2 = _features_validity(test)
    val_model = GradientBoostingClassifier(random_state=7).fit(Xtr2, ytr2)
    proba = val_model.predict_proba(Xte2)[:, 1]
    auc = float(roc_auc_score(yte2, proba)) if len(set(yte2)) > 1 else 0.0
    metrics = {"delay_mae_days": round(mae, 3), "delay_baseline_mae_days": round(baseline_mae, 3),
               "validity_auc": round(auc, 3), "train_rows": len(train), "test_rows": len(test),
               "data_basis": "synthetic generator with learnable customer/amount/seasonality signal (seed data); retrain on real history when available"}
    if artifact_dir:
        os.makedirs(artifact_dir, exist_ok=True)
        with open(os.path.join(artifact_dir, "models.pkl"), "wb") as f:
            pickle.dump({"delay": delay_model, "validity": val_model}, f)
        with open(os.path.join(artifact_dir, "metrics.json"), "w") as f:
            json.dump(metrics, f, indent=2)
    return {"delay_model": delay_model, "validity_model": val_model, "metrics": metrics}

def predict_delay(model, customer, terms_days, amount_cents, month):
    custs = sorted(CUSTOMER_PROFILES)
    onehot = [1.0 if customer == c else 0.0 for c in custs]
    x = np.array([onehot + [terms_days, np.log1p(amount_cents), month, 1.0 if month in (3, 6, 9, 12) else 0.0]])
    return float(model.predict(x)[0])

def predict_validity(model, pod_clean, claim_ratio, amount_cents, terms_days):
    x = np.array([[1 if pod_clean else 0, claim_ratio, np.log1p(amount_cents), terms_days]])
    return float(model.predict_proba(x)[0][1])
